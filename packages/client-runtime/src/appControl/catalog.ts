export type AppCommandId = (typeof APP_COMMAND_CATALOG)[number]["id"];

export const APP_COMMAND_IDS = APP_COMMAND_CATALOG.map(
  ({ id }) => id,
) as ReadonlyArray<AppCommandId>;

export function getAppCommandCatalogEntry(commandId: string): AppCommandCatalogEntry | undefined {
  return APP_COMMAND_CATALOG.find(({ id }) => id === commandId);
}

export function isAppCommandId(value: string): value is AppCommandId {
  return APP_COMMAND_IDS.includes(value as AppCommandId);
}

