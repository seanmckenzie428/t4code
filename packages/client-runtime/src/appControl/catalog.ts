export function appCommandIdForKeybinding(commandId: string): AppCommandId | null {
  if (commandId.startsWith("script.") && commandId.endsWith(".run")) return "script.run";
  const modelJump = /^modelPicker\.jump\.([1-9])$/.exec(commandId);
  if (modelJump) return `ui.model-picker.jump.${modelJump[1]}` as AppCommandId;
  const threadJump = /^thread\.jump\.([1-9])$/.exec(commandId);
  if (threadJump) return `ui.thread.jump.${threadJump[1]}` as AppCommandId;
  return (
    KEYBINDING_APP_COMMAND_ALIASES[commandId as keyof typeof KEYBINDING_APP_COMMAND_ALIASES] ?? null
  );
}
